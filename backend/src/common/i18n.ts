export type Lang = 'pt' | 'en';

export function requestLang(req: Pick<Request, 'headers'>): Lang {
  const header = req.headers['x-lang'];
  return (Array.isArray(header) ? header[0] : header)?.toLowerCase().startsWith('en') ? 'en' : 'pt';
}

