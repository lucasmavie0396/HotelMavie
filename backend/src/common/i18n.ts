export function translateMessage(message: string, lang: Lang) {
  if (lang === 'pt') return message;
  const exact = EXACT[message];
  if (exact) return exact;
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(message)) return message.replace(pattern, replacement);
  }
  return message;
}

export function translateErrors(req: Request, res: Response, next: NextFunction) {
  const lang = requestLang(req);
  if (lang !== 'pt') {
    const json = res.json.bind(res);
    res.json = (body: unknown) => {
      if (res.statusCode >= 400 && body && typeof body === 'object' && 'message' in body) {
        const message = (body as { message: unknown }).message;
        const translated = Array.isArray(message)
          ? message.map((item) => (typeof item === 'string' ? translateMessage(item, lang) : item))
          : typeof message === 'string'
            ? translateMessage(message, lang)
            : message;
        return json({ ...(body as object), message: translated });
      }
      return json(body);
    };
  }
  next();
}
